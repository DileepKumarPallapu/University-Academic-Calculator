import type { CatalogueCourse } from '../types/catalogue';

/**
 * Checks whether a regulation supports and displays course codes.
 * VTR25 strictly does NOT have course codes.
 * VTR15, VTR18, and VTR21 support course codes.
 */
export function isRegulationSupportingCourseCode(regulation: string): boolean {
  if (!regulation) return true;
  const regUpper = regulation.trim().toUpperCase();
  if (regUpper === 'VTR25' || regUpper.startsWith('VTR25')) {
    return false;
  }
  return true;
}

